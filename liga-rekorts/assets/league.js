function parseScore(s){
  // '6:4, 3:6, 10:8' → [[6,4],[3,6],[10,8]]
  return String(s||'').split(/[,;]\s*/).map(x=>x.trim().split(/[:\-–]/).map(Number)).filter(x=>x.length===2&&!isNaN(x[0])&&!isNaN(x[1]));
}
function winnerOf(m){const sets=parseScore(m.score); let a=0,b=0; sets.forEach(([x,y])=>{if(x>y)a++; else if(y>x)b++;}); return a===b?null:(a>b?'a':'b');}
/* таблица дивизиона: победы → разница сетов → разница геймов */
function standings(div){
  const rows={};
  const row=n=>rows[n]||(rows[n]={pair:n,p:0,w:0,l:0,sf:0,sa:0,gf:0,ga:0});
  MATCHES.filter(m=>m.div===div&&m.score&&m.stage!=='Плей-офф'&&m.stage!=='Финал').forEach(m=>{
    const A=row(m.a), B=row(m.b), w=winnerOf(m);
    A.p++; B.p++;
    parseScore(m.score).forEach(([x,y])=>{A.gf+=x;A.ga+=y;B.gf+=y;B.ga+=x; if(x>y){A.sf++;B.sa++;} else if(y>x){B.sf++;A.sa++;}});
    if(w==='a'){A.w++;B.l++;} else if(w==='b'){B.w++;A.l++;}
  });
  // пары из состава, ещё не сыгравшие, тоже в таблице
  (PAIRS[div]||[]).forEach(p=>row(pairTitle(p)));
  return Object.values(rows).sort((x,y)=>y.w-x.w||(y.sf-y.sa)-(x.sf-x.sa)||(y.gf-y.ga)-(x.gf-x.ga)||x.pair.localeCompare(y.pair,'ru'));
}
